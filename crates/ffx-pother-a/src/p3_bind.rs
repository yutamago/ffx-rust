//! The classes' `Bind` functions (cdecl `()`): each registers its class
//! descriptor with the type dispenser, makes its member descriptors once
//! (one bit of a guard word each, an `atexit` destructor after each), sets
//! up the method callers, and adds the descriptor to its namespace (that
//! call's `eax` is the function's).
//!
//! Every `Bind` here follows the same few shapes, so a port is a table of
//! [`Step`]s in the original's order, run by [`bridge::bind`]. The tables
//! were read off the disassembly (one step per original store or call;
//! exception frames and cookies left out) and are proven by the parity
//! tests, which run every table against its original.

use crate::{cdecl, thiscall};
use ffx_graphic::host::Host;

/// `Phyre_PTypeDispenser_RegisterType` (cdecl `(descriptor)`).
pub const REGISTER_TYPE: u32 = 0x0043_95b0;
/// `Phyre_PClassDescriptor_addToNamespace` (thiscall `(descriptor)`).
pub const ADD_TO_NAMESPACE: u32 = 0x0043_c140;
/// `atexit` (cdecl `(f)`).
pub const ATEXIT: u32 = 0x0094_9207;
/// The data member constructors (thiscall `(member, descriptor, type,
/// name, offset, size, flags)`): `PClassDataMember`,
/// `PClassDataMemberArrayFixedSize`, `PClassDataMemberArray`.
pub const DATA: u32 = 0x0057_52a0;
pub const DATA_FIXED: u32 = 0x0057_5f30;
pub const DATA_ARRAY: u32 = 0x0057_5ef0;
/// `0x0057_5370` (thiscall, the same six words): the descriptor
/// wrappers' data member constructor.
pub const DATA_WRAPPED: u32 = 0x0057_5370;
/// `Phyre_PNamespace_GetGlobalNamespace` (cdecl `()`).
pub const GLOBAL_NAMESPACE: u32 = 0x0043_e2f0;
/// `Phyre_PClassDescriptor_PClassDescriptor` (thiscall `(d, ns, name,
/// size, align)`).
pub const CLASS_DESCRIPTOR_INIT: u32 = 0x0043_afb0;
/// `Phyre_PClassMember_PClassMember` (thiscall `(member, descriptor, name,
/// 0)`).
pub const CLASS_MEMBER: u32 = 0x0043_a080;

/// Where a method member looks for a namesake before linking itself into
/// its owner's list: the finder (thiscall `(owner, name)`) and the list's
/// offset in the owner.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Find {
    pub finder: u32,
    pub list: u32,
}

/// `Phyre_findNamed_004306b0`, the list at `+0x54` (functions).
pub const FIND_FUNCTION: Find = Find {
    finder: 0x0043_06b0,
    list: 0x54,
};
/// `Phyre_PClassDescriptor_findMember_004359d0`, the list at `+0x4c`
/// (methods).
pub const FIND_METHOD: Find = Find {
    finder: 0x0043_59d0,
    list: 0x4c,
};

/// A data member's type descriptor.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ty {
    /// A descriptor in the image.
    Addr(u32),
    /// A type dispenser getter's result (cdecl `()`), called after the
    /// guard bit is set.
    Get(u32),
}

/// One step of a `Bind`, in the original's order. Addresses are
/// `ffx.sym` addresses (rebased when run).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Step {
    /// `RegisterType(descriptor)`; the descriptor of the steps after it.
    Register(u32),
    /// The guard word of the [`Step::Once`] blocks after it.
    Guard(u32),
    /// Runs the steps up to the next [`Step::End`] once: when the guard's
    /// `bit` is clear, sets it and runs them; else skips them.
    Once(u32),
    /// The end of a [`Step::Once`] block.
    End,
    /// A data member: `ctor(member, descriptor, type, name, offset, size,
    /// flags)`.
    Member {
        ctor: u32,
        member: u32,
        ty: Ty,
        name: u32,
        offset: u32,
        size: u32,
        flags: u32,
    },
    /// A method member: `PClassMember(member, descriptor, name, 0)`; its
    /// caller word (`+0x14`) cleared; then, when it has a name (`+0xc`) and
    /// the finder finds no namesake in its owner (`+8`), it is linked last
    /// into the owner's list (`{first, last}`).
    Method { member: u32, name: u32, find: Find },
    /// `atexit(f)`.
    AtExit(u32),
    /// `*a = v` (both addresses).
    Store(u32, u32),
    /// `*a = 0`.
    Zero(u32),
    /// `*a |= v`.
    Or(u32, u32),
    /// `addToNamespace(descriptor)`, the `eax` returned.
    AddToNamespace,
    /// `PClassDescriptor(descriptor, GetGlobalNamespace(), name, size,
    /// align)`; the descriptor of the steps after it.
    Descriptor {
        descriptor: u32,
        name: u32,
        size: u32,
        align: u32,
    },
    /// Runs the steps up to the next [`Step::EndIf`] when the byte at the
    /// address is 0.
    IfZeroByte(u32),
    /// The end of a [`Step::IfZeroByte`] block.
    EndIf,
    /// `*(u8 *)a = v`.
    StoreByte(u32, u8),
    /// The descriptor returned (the wrappers' getters), not the namespace
    /// call's `eax`.
    ReturnDescriptor,
}

pub mod bridge {
    //! The originals over game memory.

    use super::{
        ADD_TO_NAMESPACE, ATEXIT, CLASS_DESCRIPTOR_INIT, CLASS_MEMBER, Find, GLOBAL_NAMESPACE,
        Host, REGISTER_TYPE, Step, Ty, cdecl, thiscall,
    };

    /// The index of the next `end` step from `i` (or the table's end).
    fn skip(steps: &[Step], mut i: usize, end: Step) -> usize {
        while i < steps.len() && steps[i] != end {
            i += 1;
        }
        i
    }

    /// A [`Step::Method`] of the class `d`.
    fn method(h: &mut impl Host, d: u32, member: u32, name: u32, find: Find) {
        let m = h.rebase(member);
        let n = h.rebase(name);
        thiscall(h, CLASS_MEMBER, m, &[d, n, 0]);
        let owner: u32 = h.read(m + 8);
        let own_name: u32 = h.read(m + 0xc);
        h.write(m + 0x14, 0u32);
        let list = owner.wrapping_add(find.list);
        if own_name != 0 && thiscall(h, find.finder, owner, &[own_name]) == 0 {
            let last: u32 = h.read(list.wrapping_add(4));
            h.write(m, list);
            h.write(m + 4, last);
            h.write(last, m);
            h.write(list.wrapping_add(4), m);
        }
    }

    /// Runs a `Bind` table; `eax` as the original returns it (the
    /// namespace call's).
    pub fn bind(h: &mut impl Host, steps: &[Step]) -> u32 {
        // the class's descriptor: the original pushes it as an immediate,
        // so the members and the result use it even when the block that
        // constructs it (a wrapper's first `Once`) is skipped
        let mut d = steps
            .iter()
            .find_map(|s| match *s {
                Step::Register(x) | Step::Descriptor { descriptor: x, .. } => Some(x),
                _ => None,
            })
            .map_or(0, |x| h.rebase(x));
        let mut guard = 0;
        let mut eax = 0;
        let mut i = 0;
        while i < steps.len() {
            match steps[i] {
                Step::Register(x) => {
                    d = h.rebase(x);
                    cdecl(h, REGISTER_TYPE, &[d]);
                }
                Step::Guard(g) => guard = h.rebase(g),
                Step::Once(bit) => {
                    let w: u32 = h.read(guard);
                    if w & bit == 0 {
                        h.write(guard, w | bit);
                    } else {
                        i = skip(steps, i, Step::End);
                    }
                }
                Step::Member {
                    ctor,
                    member,
                    ty,
                    name,
                    offset,
                    size,
                    flags,
                } => {
                    let t = match ty {
                        Ty::Addr(a) => h.rebase(a),
                        Ty::Get(f) => cdecl(h, f, &[]),
                    };
                    let (m, n) = (h.rebase(member), h.rebase(name));
                    thiscall(h, ctor, m, &[d, t, n, offset, size, flags]);
                }
                Step::Method { member, name, find } => method(h, d, member, name, find),
                Step::AtExit(f) => {
                    let f = h.rebase(f);
                    cdecl(h, ATEXIT, &[f]);
                }
                Step::Store(a, v) => {
                    let (a, v) = (h.rebase(a), h.rebase(v));
                    h.write(a, v);
                }
                Step::Zero(a) => {
                    let a = h.rebase(a);
                    h.write(a, 0u32);
                }
                Step::Or(a, v) => {
                    let a = h.rebase(a);
                    let w: u32 = h.read(a);
                    h.write(a, w | v);
                }
                Step::AddToNamespace => eax = thiscall(h, ADD_TO_NAMESPACE, d, &[]),
                Step::Descriptor {
                    descriptor,
                    name,
                    size,
                    align,
                } => {
                    d = h.rebase(descriptor);
                    let n = h.rebase(name);
                    let ns = cdecl(h, GLOBAL_NAMESPACE, &[]);
                    thiscall(h, CLASS_DESCRIPTOR_INIT, d, &[ns, n, size, align]);
                }
                Step::IfZeroByte(a) => {
                    let a = h.rebase(a);
                    if h.read::<u8>(a) != 0 {
                        i = skip(steps, i, Step::EndIf);
                    }
                }
                // the ends of the blocks
                Step::End | Step::EndIf => {}
                Step::StoreByte(a, v) => {
                    let a = h.rebase(a);
                    h.write(a, v);
                }
                Step::ReturnDescriptor => eax = d,
            }
            i += 1;
        }
        eax
    }
}

