//! Iggy's image over the game's target (docs/host.md, "Iggy"): where the
//! original's `IggyPlayerDraw` has `GDraw` draw the movie into the view
//! `gdraw_setRenderTargetView_00a38300` set (the back buffer, after the
//! scene: `IggyMenuManager_Render_00a267f0`), the layer draws the Flash
//! player's image there, on the immediate context, in the same place of
//! the render thread's commands:
//!
//! - a texture of the image (`R8G8B8A8_UNORM`, premultiplied, updated with
//!   each draw) and its view;
//! - a quad over the image's rectangle (the viewport at `GDraw`'s origin,
//!   one texel per pixel: `Load`, no filtering), no depth target;
//! - `GDraw`'s blend for every draw the pilot logged (blend state 1,
//!   `ONE`, `INV_SRC_ALPHA`: premultiplied alpha; docs/formats/pc-ui.md,
//!   "How Iggy draws"), no culling, no scissor;
//! - then everything it changed goes back to what the game had bound (the
//!   layer's [`super::Bound`]), so the game's next calls see their own
//!   state, as after `GDraw`.
//!
//! The objects are the layer's own (ids from [`OWN`] up, never a game
//! handle: those are arena addresses below the stub regions), made on the
//! back end directly and left out of the recording: the stream holds what
//! the game drew, and the original's `GDraw` draws stay the allowed
//! difference (`docs/host.md`, "The first comparison").
//!
//! The shaders are `composite.hlsl` beside this file, compiled with the
//! Windows SDK's `fxc` (`tools/host-composite-shaders.sh` prints the
//! arrays below): `vs_4_0` / `ps_4_0`, `/O3`.

use super::{Create, Gfx, Op};
use crate::com_methods::class;
use ffx_gfx::{DrawKind, StateKind};

/// The layer's own object ids.
const OWN: u32 = 0xffff_ff00;
const VS: u32 = OWN;
const PS: u32 = OWN + 1;
const BLEND: u32 = OWN + 2;
const RASTER: u32 = OWN + 3;
const TEXTURE: u32 = OWN + 4;
const VIEW: u32 = OWN + 5;

/// `DXGI_FORMAT_R8G8B8A8_UNORM`.
const RGBA8: u32 = 28;
/// `D3D11_PRIMITIVE_TOPOLOGY_TRIANGLESTRIP`.
const STRIP: u32 = 5;

/// The objects once made: whether the shaders and states are, and the
/// texture's size.
#[derive(Debug, Default)]
pub(super) struct Objects {
    made: bool,
    size: (u32, u32),
}

/// `D3D11_BLEND_DESC`: no alpha to coverage, one target: `ONE`,
/// `INV_SRC_ALPHA`, `ADD` for colour and alpha, all channels written.
fn blend_desc() -> Vec<u8> {
    let mut words = vec![0u32, 0];
    // BlendEnable, Src ONE (2), Dest INV_SRC_ALPHA (6), ADD (1), the same
    // for alpha, write mask 0xf
    words.extend([1, 2, 6, 1, 2, 6, 1, 0xf]);
    // targets 1-7 unused
    words.extend(std::iter::repeat_n(0, 8 * 7));
    words.iter().flat_map(|w| w.to_le_bytes()).collect()
}

/// `D3D11_RASTERIZER_DESC`: solid (3), no culling (1), depth clip on,
/// no scissor, no multisampling.
fn raster_desc() -> Vec<u8> {
    [3u32, 1, 0, 0, 0, 0, 1, 0, 0, 0]
        .iter()
        .flat_map(|w| w.to_le_bytes())
        .collect()
}

impl Gfx {
    fn composite_objects(&mut self, (w, h): (u32, u32), rows: &[u8]) -> bool {
        let ok = |hr: u32| hr >> 31 == 0;
        if !self.composite.made {
            let made = ok(self.backend.create(
                VS,
                &Create::Shader {
                    stage: b'v',
                    bytecode: &VS_DXBC,
                },
            )) && ok(self.backend.create(
                PS,
                &Create::Shader {
                    stage: b'p',
                    bytecode: &PS_DXBC,
                },
            )) && ok(self.backend.create(
                BLEND,
                &Create::State {
                    kind: StateKind::Blend,
                    desc: &blend_desc(),
                },
            )) && ok(self.backend.create(
                RASTER,
                &Create::State {
                    kind: StateKind::Raster,
                    desc: &raster_desc(),
                },
            ));
            if !made {
                return false;
            }
            self.composite.made = true;
        }
        if self.composite.size == (w, h) {
            self.backend
                .op(&Op::Update(TEXTURE, 0, None, rows, w * 4, 0));
        } else {
            self.backend.release(VIEW);
            self.backend.release(TEXTURE);
            self.composite.size = (0, 0);
            // width, height, 1 mip, 1 layer, RGBA8, 1 sample, DEFAULT,
            // SHADER_RESOURCE, no CPU access, no flags
            let desc = [w, h, 1, 1, RGBA8, 1, 0, 0, 0x8, 0, 0];
            let init = [(w * 4, 0, rows.to_vec())];
            let made = ok(self.backend.create(
                TEXTURE,
                &Create::Texture {
                    dims: 2,
                    desc: &desc,
                    init: &init,
                },
            )) && ok(self.backend.create(
                VIEW,
                &Create::View {
                    class: class::SRV,
                    resource: TEXTURE,
                    desc: None,
                },
            ));
            if !made {
                return false;
            }
            self.composite.size = (w, h);
        }
        true
    }

    /// Draws `rows` (`w` x `h`, premultiplied RGBA) over the render target
    /// view `target` with its top left at `origin`, then rebinds what the
    /// game had bound. False when the image or the objects are missing.
    pub fn composite(
        &mut self,
        target: u32,
        origin: (i32, i32),
        (w, h): (u32, u32),
        rows: &[u8],
    ) -> bool {
        if w == 0 || h == 0 || rows.len() < (w as usize) * (h as usize) * 4 {
            return false;
        }
        if !self.composite_objects((w, h), rows) {
            return false;
        }
        #[allow(clippy::cast_precision_loss)]
        let viewport = [
            origin.0 as f32,
            origin.1 as f32,
            w as f32,
            h as f32,
            0.0,
            1.0,
        ];
        let b = &mut self.backend;
        b.op(&Op::Targets(&[target], 0));
        b.op(&Op::Viewports(&[viewport]));
        b.op(&Op::Raster(RASTER));
        b.op(&Op::Blend(BLEND, [1.0; 4], u32::MAX));
        b.op(&Op::InputLayout(0));
        b.op(&Op::Topology(STRIP));
        b.op(&Op::Shader(b'v', VS));
        b.op(&Op::Shader(b'g', 0));
        b.op(&Op::Shader(b'p', PS));
        b.op(&Op::Resources(b'p', 0, &[VIEW]));
        b.op(&Op::Draw(DrawKind::Plain, [4, 0, 0, 0, 0]));
        self.rebind();
        true
    }

    /// Binds again what the composite changed, from the layer's record of
    /// the game's state.
    fn rebind(&mut self) {
        let s = &self.bound;
        let b = &mut self.backend;
        b.op(&Op::Resources(b'p', 0, &[s.ps_srv[0]]));
        let n = s.rtv.iter().rposition(|&v| v != 0).map_or(0, |i| i + 1);
        b.op(&Op::Targets(&s.rtv[..n], s.dsv));
        b.op(&Op::Viewports(&[s.viewport]));
        b.op(&Op::Raster(s.raster));
        b.op(&Op::Blend(s.blend, s.blend_factor, s.sample_mask));
        b.op(&Op::InputLayout(s.layout));
        b.op(&Op::Topology(s.topology));
        b.op(&Op::Shader(b'v', s.vs));
        b.op(&Op::Shader(b'g', s.gs));
        b.op(&Op::Shader(b'p', s.ps));
    }
}

