/// A `CallArg` row: `func(arg)` (cdecl, one image address); its `eax`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CallArg {
    pub addr: u32,
    pub func: u32,
    pub arg: u32,
}

/// The `CallArg` shims' body.
pub fn call_arg(h: &mut impl Host, r: &CallArg) -> u32 {
    let arg = h.rebase(r.arg);
    h.call_sym(r.func, Conv::Cdecl, &[arg])
}

/// A `VtTail` row: the vtable `vt` goes into the object `obj`, then the
/// original jumps to `target` with `ecx = obj` (thiscall), which returns to
/// our caller; its `eax` is ours.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VtTail {
    pub addr: u32,
    pub obj: u32,
    pub vt: u32,
    pub target: u32,
}

/// The `VtTail` shims' body.
pub fn vt_tail(h: &mut impl Host, r: &VtTail) -> u32 {
    let obj = h.rebase(r.obj);
    let vt = h.rebase(r.vt);
    h.write(obj, vt);
    h.call_sym(r.target, Conv::Thiscall(obj), &[])
}

/// A `StoreWord` row: the image address `value` (a vtable) goes into the
/// global `g`. The original leaves `eax` alone (a void shim).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StoreWord {
    pub addr: u32,
    pub g: u32,
    pub value: u32,
}

/// The `StoreWord` shims' body.
pub fn store_word(h: &mut impl Host, r: &StoreWord) {
    let g = h.rebase(r.g);
    let v = h.rebase(r.value);
    h.write(g, v);
}

/// An `ImportWord` row: the stdcall import in the slot `iat` with the word
/// at the global `g`; its `eax`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ImportWord {
    pub addr: u32,
    pub iat: u32,
    pub g: u32,
}

/// The `ImportWord` shims' body.
pub fn import_word(h: &mut impl Host, r: &ImportWord) -> u32 {
    let g = h.rebase(r.g);
    let w: u32 = h.read(g);
    let slot = h.rebase(r.iat);
    let f: u32 = h.read(slot);
    h.call(f, Conv::Stdcall, &[w])
}

/// A `VtCall` row: the vtable `vt` goes into the object `obj`, then
/// `func(obj)` (cdecl); its `eax`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VtCall {
    pub addr: u32,
    pub obj: u32,
    pub vt: u32,
    pub func: u32,
}

/// The `VtCall` shims' body.
pub fn vt_call(h: &mut impl Host, r: &VtCall) -> u32 {
    let obj = h.rebase(r.obj);
    let vt = h.rebase(r.vt);
    h.write(obj, vt);
    h.call_sym(r.func, Conv::Cdecl, &[obj])
}

/// A `FreeUnlessBit0` row: the word at `g`; when its bit 0 is clear,
/// `func(word)` (cdecl) and its `eax`, else the word itself (the original
/// returns with it in `eax`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FreeUnlessBit0 {
    pub addr: u32,
    pub g: u32,
    pub func: u32,
}

/// The `FreeUnlessBit0` shims' body.
pub fn free_unless_bit0(h: &mut impl Host, r: &FreeUnlessBit0) -> u32 {
    let g = h.rebase(r.g);
    let w: u32 = h.read(g);
    if w & 1 == 0 {
        h.call_sym(r.func, Conv::Cdecl, &[w])
    } else {
        w
    }
}

