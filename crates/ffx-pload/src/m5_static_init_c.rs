//! M5 stage 1, list `static-init-c`: compiler-generated constructors of
//! globals (the CRT's dynamic initialisers, which run before `WinMain`) and
//! the destructors they register with `atexit`.
//!
//! The shapes static-init-b found are reused as they are (its row types and
//! bridges, re-exported here); this module adds its own rows and the shapes
//! that list did not have. Each address is one shim in `ffx-hook`
//! (`ported/m5_static_init_c.rs`) that calls its row. An image address in a
//! row (a global, a vtable, a string, a destructor) is rebased before use; a
//! plain number goes as it is. Callees outside the list stay calls to the
//! original (`call_sym`). The parity tests are
//! `crates/ffx-oracle/tests/m5_static_init_c.rs`.

use ffx_graphic::host::{Conv, Host};

pub use crate::m5_static_init_b::{
    Base, CLASS_CTOR, ClassDecl, Ctor0AtExit, GET_CLASS_DESCRIPTOR, GET_GLOBAL_NAMESPACE,
    ListAppend, NamedType, SET_DEFAULT_BUFFER, SET_VALIDATION_BUFFER, SET_WRITE_MASK_BUFFER, Tail,
    TypeEnum, at_exit, class_decl, ctor0_at_exit, list_append, named_type, type_enum,
};

/// A `ZeroWords` row (1): the globals `words` are set to 0, in order. The
/// original leaves `eax` alone (a void shim).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ZeroWords {
    pub addr: u32,
    pub words: &'static [u32],
}

/// The `ZeroWords` shims' body.
pub fn zero_words(h: &mut impl Host, r: &ZeroWords) {
    for &w in r.words {
        let at = h.rebase(w);
        h.write(at, 0u32);
    }
}

/// An `ImportAtExit` row (1): the stdcall import in the slot `iat` with the
/// one word `arg` (an image address), then `atexit(dtor)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ImportAtExit {
    pub addr: u32,
    pub iat: u32,
    pub arg: u32,
    pub dtor: u32,
}

/// The `ImportAtExit` shims' body: the `atexit` result.
pub fn import_at_exit(h: &mut impl Host, r: &ImportAtExit) -> u32 {
    let slot = h.rebase(r.iat);
    let f: u32 = h.read(slot);
    let arg = h.rebase(r.arg);
    h.call(f, Conv::Stdcall, &[arg]);
    at_exit(h, r.dtor)
}

/// A class descriptor declaration whose tail also stores a function pointer
/// (`ClassDeclFn`, 1): the base from `GetClassDescriptor()`, the
/// constructor, flags bit 1, the vtable `vt1` and the three buffers as in
/// [`ClassDecl`]; then `flags = ((flags & !2) | 0xc) & !8`, `func` at
/// `flags + 4`, the vtable `vt2`; `atexit(dtor)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ClassDeclFn {
    pub addr: u32,
    pub obj: u32,
    pub flags: u32,
    pub name: u32,
    pub size: u32,
    pub align: u32,
    pub c: u32,
    pub def: u32,
    pub val: u32,
    pub wm: u32,
    pub vt1: u32,
    pub func: u32,
    pub vt2: u32,
    pub dtor: u32,
}

/// The `ClassDeclFn` shims' body: the `atexit` result.
pub fn class_decl_fn(h: &mut impl Host, r: &ClassDeclFn) -> u32 {
    // GetClassDescriptor runs before GetGlobalNamespace, as in the original
    let base = h.call_sym(GET_CLASS_DESCRIPTOR, Conv::Cdecl, &[]);
    let ns = h.call_sym(GET_GLOBAL_NAMESPACE, Conv::Cdecl, &[]);
    let obj = h.rebase(r.obj);
    let flags = h.rebase(r.flags);
    let name = h.rebase(r.name);
    h.call_sym(
        CLASS_CTOR,
        Conv::Thiscall(obj),
        &[ns, name, r.size, r.align, base, r.c],
    );
    let f: u32 = h.read(flags);
    h.write(flags, f | 2);
    let vt1 = h.rebase(r.vt1);
    h.write(obj, vt1);
    let def = h.rebase(r.def);
    h.call_sym(SET_DEFAULT_BUFFER, Conv::Thiscall(obj), &[def]);
    let val = h.rebase(r.val);
    h.call_sym(SET_VALIDATION_BUFFER, Conv::Thiscall(obj), &[val]);
    let wm = h.rebase(r.wm);
    h.call_sym(SET_WRITE_MASK_BUFFER, Conv::Thiscall(obj), &[wm]);
    // the original computes the flags in eax, stores the function word and
    // the vtable, then the flags
    let f: u32 = h.read(flags);
    let f = ((f & !2) | 0xc) & !8;
    let func = h.rebase(r.func);
    h.write(flags + 4, func);
    let vt2 = h.rebase(r.vt2);
    h.write(obj, vt2);
    h.write(flags, f);
    at_exit(h, r.dtor)
}

