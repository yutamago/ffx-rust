//! M5 stage 1, list `static-init-c`: compiler-generated constructors of
//! globals (the CRT's dynamic initialisers, which run before `WinMain`) and
//! the destructors they register with `atexit`.
//!
//! The shapes static-init-b found are reused as they are (its row types and
//! bridges, re-exported here); this module adds its own rows and the shapes
//! that list did not have. Each address is one shim in `ffx-hook`
//! (`ported/m5_static_init_c.rs`) that calls its row. An image address in a
//! row (a global, a vtable, a string, a destructor) is rebased before use; a
//! plain number goes as it is. Callees outside the list stay calls to the
//! original (`call_sym`). The parity tests are
//! `crates/ffx-oracle/tests/m5_static_init_c.rs`.

