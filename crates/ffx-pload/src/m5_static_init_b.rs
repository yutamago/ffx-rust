//! M5 stage 1, list `static-init-b`: the compiler-generated constructors of
//! globals (the CRT's dynamic initialisers, which run before `WinMain`) and
//! the destructors they register with `atexit`.
//!
//! Each family is one bridge over its rows (`TYPE_ENUMS`, `CLASS_DECLS`, ...);
//! each address is one shim in `ffx-hook` (`ported/m5_static_init_b.rs`)
//! that calls its row. The rows are the original's constants. An image
//! address (a global, a vtable, a string, a destructor) is rebased before
//! use; a plain number goes as it is. The callees are the original code,
//! called at their addresses (`call_sym`), as the other lists do.
//!
//! Every shim returns what the original leaves in `eax`: the `atexit`
//! result, which the CRT's initialiser loop ignores.

use ffx_graphic::host::{Conv, Host};

/// CRT `atexit(fn)`, cdecl.
pub const ATEXIT: u32 = 0x0094_9207;
/// `PNamespace::GetGlobalNamespace()`, cdecl.
pub const GET_GLOBAL_NAMESPACE: u32 = 0x0043_e2f0;
/// `PBase::GetClassDescriptor()`, cdecl.
pub const GET_CLASS_DESCRIPTOR: u32 = 0x0043_5740;
/// `PClassDescriptor::PClassDescriptor(ns, name, size, align, base, c)`,
/// thiscall, `ret 0x18`.
pub const CLASS_CTOR: u32 = 0x0043_b0a0;
/// `PClassDescriptor::setDefaultBuffer(buf)`, thiscall, `ret 4`.
pub const SET_DEFAULT_BUFFER: u32 = 0x0043_d510;
/// `PClassDescriptor::setValidationBuffer(buf)`, thiscall, `ret 4`.
pub const SET_VALIDATION_BUFFER: u32 = 0x0043_d5b0;
/// `PClassDescriptor::setWriteMaskBuffer(buf)`, thiscall, `ret 4`.
pub const SET_WRITE_MASK_BUFFER: u32 = 0x0043_d5c0;
/// `PSceneRenderPassType::PSceneRenderPassType(name, flag)`, thiscall,
/// `ret 8`.
pub const PASS_TYPE_CTOR: u32 = 0x004d_b230;

/// `atexit(dtor)`: registers the destructor, returns the CRT's result.
pub fn at_exit(h: &mut impl Host, dtor: u32) -> u32 {
    let f = h.rebase(dtor);
    h.call_sym(ATEXIT, Conv::Cdecl, &[f])
}

/// A `typeenum` row (150): `if (find(name) == 0) { node.next = head;
/// head = node; } atexit(dtor)`. `find` is one of the enum-value lookups
/// (`0x009f48f0` and three more, each over its own list head).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TypeEnum {
    pub addr: u32,
    pub find: u32,
    pub name: u32,
    pub head: u32,
    pub node: u32,
    pub next: u32,
    pub dtor: u32,
}

/// The `typeenum` shims' body.
pub fn type_enum(h: &mut impl Host, r: &TypeEnum) -> u32 {
    let name = h.rebase(r.name);
    if h.call_sym(r.find, Conv::Cdecl, &[name]) == 0 {
        let head = h.rebase(r.head);
        let old: u32 = h.read(head);
        let link = h.rebase(r.next);
        h.write(link, old);
        let node = h.rebase(r.node);
        h.write(head, node);
    }
    at_exit(h, r.dtor)
}

/// A `namedtype` row (97): `PSceneRenderPassType` built in place on a
/// global (`this`, name, flag), then `atexit(dtor)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NamedType {
    pub addr: u32,
    pub obj: u32,
    pub name: u32,
    pub flag: u32,
    pub dtor: u32,
}

/// The `namedtype` shims' body.
pub fn named_type(h: &mut impl Host, r: &NamedType) -> u32 {
    let obj = h.rebase(r.obj);
    let name = h.rebase(r.name);
    h.call_sym(PASS_TYPE_CTOR, Conv::Thiscall(obj), &[name, r.flag]);
    at_exit(h, r.dtor)
}

/// An `atexit`-only row (7): the destructor is registered and nothing else.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AtExitOnly {
    pub addr: u32,
    pub dtor: u32,
}

/// The `atexit`-only shims' body.
pub fn at_exit_only(h: &mut impl Host, r: &AtExitOnly) -> u32 {
    at_exit(h, r.dtor)
}

/// A `ctor0_atexit` row (5): a no-argument constructor on a global
/// (thiscall), then `atexit(dtor)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Ctor0AtExit {
    pub addr: u32,
    pub ctor: u32,
    pub obj: u32,
    pub dtor: u32,
}

/// The `ctor0_atexit` shims' body.
pub fn ctor0_at_exit(h: &mut impl Host, r: &Ctor0AtExit) -> u32 {
    let obj = h.rebase(r.obj);
    h.call_sym(r.ctor, Conv::Thiscall(obj), &[]);
    at_exit(h, r.dtor)
}

/// A `ctor0_flags_vt` row (4, and static-init-ab's): a no-argument
/// constructor on a global, then `flags = (flags & ~2) | set`, the object's
/// vtable, `atexit(dtor)`. `set` is 0 (`and` alone) or 8 (the originals
/// that also `or eax, 8`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Ctor0FlagsVt {
    pub addr: u32,
    pub ctor: u32,
    pub obj: u32,
    pub flags: u32,
    pub set: u32,
    pub vt: u32,
    pub dtor: u32,
}

/// The `ctor0_flags_vt` shims' body.
pub fn ctor0_flags_vt(h: &mut impl Host, r: &Ctor0FlagsVt) -> u32 {
    let obj = h.rebase(r.obj);
    h.call_sym(r.ctor, Conv::Thiscall(obj), &[]);
    let flags = h.rebase(r.flags);
    let f: u32 = h.read(flags);
    h.write(flags, (f & !2) | r.set);
    let vt = h.rebase(r.vt);
    h.write(obj, vt);
    at_exit(h, r.dtor)
}

/// Where a class descriptor's base is: a global's address, or what
/// `GetClassDescriptor()` returns.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Base {
    Const(u32),
    Descriptor,
}

/// How the declaration ends: `flags &= ~2` and the final vtable (`Clear`),
/// the same with `flags |= 8` (`ClearSet8`), or neither (`Keep`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Tail {
    Clear(u32),
    ClearSet8(u32),
    Keep,
}

/// A class descriptor declaration (`cd_*`, 109 rows): the global's
/// `PClassDescriptor` constructor with the namespace, name, size, alignment,
/// base and `c`; flags bit 1 set; the three buffers, with the vtable
/// written before the first; the tail; `atexit(dtor)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ClassDecl {
    pub addr: u32,
    pub obj: u32,
    pub flags: u32,
    pub name: u32,
    pub size: u32,
    pub align: u32,
    pub base: Base,
    pub c: u32,
    pub def: u32,
    pub val: u32,
    pub wm: u32,
    pub vt1: u32,
    pub tail: Tail,
    pub dtor: u32,
}

/// The class declarations' shims' body.
pub fn class_decl(h: &mut impl Host, r: &ClassDecl) -> u32 {
    // The original calls GetClassDescriptor (when the base is a call) before
    // GetGlobalNamespace; the constructor's arguments are pushed in that order.
    let base = match r.base {
        Base::Const(b) => h.rebase(b),
        Base::Descriptor => h.call_sym(GET_CLASS_DESCRIPTOR, Conv::Cdecl, &[]),
    };
    let ns = h.call_sym(GET_GLOBAL_NAMESPACE, Conv::Cdecl, &[]);
    let obj = h.rebase(r.obj);
    let flags = h.rebase(r.flags);
    let name = h.rebase(r.name);
    h.call_sym(
        CLASS_CTOR,
        Conv::Thiscall(obj),
        &[ns, name, r.size, r.align, base, r.c],
    );
    let f: u32 = h.read(flags);
    h.write(flags, f | 2);
    let vt1 = h.rebase(r.vt1);
    h.write(obj, vt1);
    let def = h.rebase(r.def);
    h.call_sym(SET_DEFAULT_BUFFER, Conv::Thiscall(obj), &[def]);
    let val = h.rebase(r.val);
    h.call_sym(SET_VALIDATION_BUFFER, Conv::Thiscall(obj), &[val]);
    let wm = h.rebase(r.wm);
    h.call_sym(SET_WRITE_MASK_BUFFER, Conv::Thiscall(obj), &[wm]);
    match r.tail {
        Tail::Clear(vt2) => {
            let f: u32 = h.read(flags);
            h.write(flags, f & !2);
            let vt2 = h.rebase(vt2);
            h.write(obj, vt2);
        }
        Tail::ClearSet8(vt2) => {
            let f: u32 = h.read(flags);
            let vt2 = h.rebase(vt2);
            h.write(obj, vt2);
            h.write(flags, (f & !2) | 8);
        }
        Tail::Keep => {}
    }
    at_exit(h, r.dtor)
}

